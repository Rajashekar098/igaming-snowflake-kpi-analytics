-- KPI 1: Monthly GGR, NGR, Hold %, and ARPU by Game Vertical
SELECT 
    DATE_TRUNC('MONTH', b.BET_DATE) AS REPORT_MONTH,
    b.GAME_CATEGORY,
    COUNT(DISTINCT b.PLAYER_ID) AS MONTHLY_ACTIVE_PLAYERS,
    COUNT(b.BET_ID) AS TOTAL_BETS_PLACED,
    SUM(b.STAKE_EUR) AS TOTAL_TURNOVER_EUR,
    SUM(b.WIN_EUR) AS TOTAL_PAYOUT_EUR,
    SUM(b.STAKE_EUR - b.WIN_EUR) AS GGR_EUR,
    ROUND(SUM(b.STAKE_EUR - b.WIN_EUR) * 0.85 - SUM(b.BONUS_COST_EUR), 2) AS NGR_EUR,
    ROUND((SUM(b.STAKE_EUR - b.WIN_EUR) / NULLIF(SUM(b.STAKE_EUR), 0)) * 100, 2) AS HOLD_PERCENTAGE,
    ROUND(SUM(b.STAKE_EUR - b.WIN_EUR) / NULLIF(COUNT(DISTINCT b.PLAYER_ID), 0), 2) AS ARPU_EUR
FROM FACT_BETS b
GROUP BY 1, 2
ORDER BY REPORT_MONTH DESC, GGR_EUR DESC;

-- KPI 2: VIP Player Tiering & Churn Risk Segmentation
WITH PlayerMetrics AS (
    SELECT 
        p.PLAYER_ID,
        p.COUNTRY_CODE,
        p.ACQUISITION_CHANNEL,
        MAX(b.BET_DATE) AS LAST_BET_DATE,
        DATEDIFF('DAY', MAX(b.BET_DATE), CURRENT_DATE()) AS DAYS_INACTIVE,
        COUNT(b.BET_ID) AS TOTAL_BETS,
        SUM(b.STAKE_EUR) AS LIFETIME_TURNOVER_EUR,
        SUM(b.STAKE_EUR - b.WIN_EUR) AS LIFETIME_GGR_EUR,
        SUM(b.STAKE_EUR - b.WIN_EUR - b.BONUS_COST_EUR) AS LIFETIME_NGR_EUR
    FROM DIM_PLAYERS p
    INNER JOIN FACT_BETS b ON p.PLAYER_ID = b.PLAYER_ID
    GROUP BY 1, 2, 3
)
SELECT 
    PLAYER_ID,
    COUNTRY_CODE,
    ACQUISITION_CHANNEL,
    LIFETIME_TURNOVER_EUR,
    LIFETIME_GGR_EUR,
    LIFETIME_NGR_EUR,
    DAYS_INACTIVE,
    CASE 
        WHEN LIFETIME_NGR_EUR >= 2500 THEN 'VIP Platinum'
        WHEN LIFETIME_NGR_EUR >= 1000 THEN 'VIP Gold'
        WHEN LIFETIME_NGR_EUR >= 250 THEN 'Standard Active'
        WHEN LIFETIME_NGR_EUR < 0 THEN 'Bonus Abuser / Sharp Player'
        ELSE 'Casual'
    END AS PLAYER_SEGMENT,
    CASE 
        WHEN DAYS_INACTIVE > 30 THEN 'Churned'
        WHEN DAYS_INACTIVE BETWEEN 14 AND 30 THEN 'At-Risk (Trigger CRM Bonus)'
        ELSE 'Retained'
    END AS RETENTION_STATUS
FROM PlayerMetrics
ORDER BY LIFETIME_NGR_EUR DESC;

-- KPI 3: Data Support Anomaly & Bonus Abuse Check
SELECT 
    PLAYER_ID,
    GAME_CATEGORY,
    BET_DATE,
    STAKE_EUR,
    WIN_EUR,
    BONUS_COST_EUR,
    ROUND(WIN_EUR / NULLIF(STAKE_EUR, 0), 2) AS PAYOUT_MULTIPLIER
FROM FACT_BETS
WHERE WIN_EUR > 500 AND BONUS_COST_EUR > 0
QUALIFY ROW_NUMBER() OVER (PARTITION BY PLAYER_ID ORDER BY WIN_EUR DESC) <= 3;