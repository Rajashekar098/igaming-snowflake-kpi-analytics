CREATE WAREHOUSE IF NOT EXISTS IGAMING_ANALYTICS_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS BRAINROCKET_IGAMING_DB;
CREATE SCHEMA IF NOT EXISTS BRAINROCKET_IGAMING_DB.CORE_KPI;

USE WAREHOUSE IGAMING_ANALYTICS_WH;
USE SCHEMA BRAINROCKET_IGAMING_DB.CORE_KPI;

CREATE OR REPLACE TABLE DIM_PLAYERS (
    PLAYER_ID INT PRIMARY KEY,
    COUNTRY_CODE VARCHAR(5),
    ACQUISITION_CHANNEL VARCHAR(50),
    REGISTRATION_DATE DATE
);

CREATE OR REPLACE TABLE FACT_BETS (
    BET_ID INT PRIMARY KEY,
    PLAYER_ID INT REFERENCES DIM_PLAYERS(PLAYER_ID),
    GAME_CATEGORY VARCHAR(30),
    BET_DATE DATE,
    STAKE_EUR NUMBER(12, 2),
    WIN_EUR NUMBER(12, 2),
    BONUS_COST_EUR NUMBER(12, 2)
)
CLUSTER BY (BET_DATE, GAME_CATEGORY);